-- Esquema STORE_APP: el ERP de la PoC. Se ejecuta como STORE_APP en FREEPDB1.
-- Solo pedidos, inventario, proveedores y movimientos. Sin CUSTOMERS (los clientes viven en Salesforce)
-- y sin remisiones (viven en el SFTP de logística). Los valores de estado van en inglés, como los contratos.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF

-- ------------------------------------------------------------------ INVENTORY
CREATE TABLE INVENTORY (
    ID           VARCHAR2(36)  NOT NULL,
    SKU          VARCHAR2(20)  NOT NULL,
    NAME         VARCHAR2(100) NOT NULL,
    STOCK_QTY    NUMBER(10)    DEFAULT 0 NOT NULL,
    LOCAL_PRICE  NUMBER(12,2)  DEFAULT 0 NOT NULL,
    CURRENCY     VARCHAR2(3)   DEFAULT 'MXN' NOT NULL,
    CREATED_AT   TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INVENTORY        PRIMARY KEY (ID),
    CONSTRAINT UQ_INVENTORY_SKU    UNIQUE (SKU),
    CONSTRAINT CHK_INV_STOCK       CHECK (STOCK_QTY >= 0),
    CONSTRAINT CHK_INV_PRICE       CHECK (LOCAL_PRICE >= 0),
    CONSTRAINT CHK_INV_CURRENCY    CHECK (REGEXP_LIKE(CURRENCY, '^[A-Z]{3}$')),
    CONSTRAINT CHK_INV_ID_UUID     CHECK (REGEXP_LIKE(ID, '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'))
);

-- --------------------------------------------------------- INVENTORY_PROVIDERS
-- Uno o más proveedores por producto y exactamente uno preferente (índice único parcial).
CREATE TABLE INVENTORY_PROVIDERS (
    ITEM_ID        VARCHAR2(36) NOT NULL,
    PROVIDER_ABV   VARCHAR2(3)  NOT NULL,
    EXTERNAL_ID    NUMBER(10)   NOT NULL,
    IS_PREFERRED   NUMBER(1)    DEFAULT 0 NOT NULL,
    LAST_PRICE     NUMBER(12,2),
    LAST_PRICE_AT  TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_INVENTORY_PROVIDERS PRIMARY KEY (ITEM_ID, PROVIDER_ABV),
    CONSTRAINT FK_INVPROV_ITEM        FOREIGN KEY (ITEM_ID) REFERENCES INVENTORY (ID),
    CONSTRAINT CHK_INVPROV_ABV        CHECK (PROVIDER_ABV IN ('FAK', 'ESC', 'BOR')),
    CONSTRAINT CHK_INVPROV_PREFERRED  CHECK (IS_PREFERRED IN (0, 1)),
    CONSTRAINT CHK_INVPROV_LAST_PRICE CHECK (LAST_PRICE IS NULL OR LAST_PRICE >= 0)
);
CREATE UNIQUE INDEX UQ_INVPROV_ONE_PREFERRED
    ON INVENTORY_PROVIDERS (CASE WHEN IS_PREFERRED = 1 THEN ITEM_ID END);

-- --------------------------------------------------------------------- ORDERS
-- Encabezado con estado. El cliente es el Id de Salesforce (18 caracteres).
CREATE TABLE ORDERS (
    ID            VARCHAR2(36)  NOT NULL,
    CUSTOMER_ID   VARCHAR2(18)  NOT NULL,
    STATUS        VARCHAR2(10)  DEFAULT 'RECEIVED' NOT NULL,
    STATUS_REASON VARCHAR2(255),
    CURRENCY      VARCHAR2(3)   DEFAULT 'MXN' NOT NULL,
    TOTAL         NUMBER(12,2),
    CREATED_AT    TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONFIRMED_AT  TIMESTAMP WITH TIME ZONE,
    UPDATED_AT    TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_ORDERS           PRIMARY KEY (ID),
    CONSTRAINT CHK_ORD_STATUS      CHECK (STATUS IN ('RECEIVED', 'CONFIRMED', 'REJECTED')),
    CONSTRAINT CHK_ORD_CUSTOMER    CHECK (REGEXP_LIKE(CUSTOMER_ID, '^[a-zA-Z0-9]{18}$')),
    CONSTRAINT CHK_ORD_CURRENCY    CHECK (REGEXP_LIKE(CURRENCY, '^[A-Z]{3}$')),
    CONSTRAINT CHK_ORD_TOTAL       CHECK (TOTAL IS NULL OR TOTAL >= 0),
    CONSTRAINT CHK_ORD_ID_UUID     CHECK (REGEXP_LIKE(ID, '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$'))
);
CREATE INDEX IX_ORDERS_STATUS_CREATED ON ORDERS (STATUS, CREATED_AT);

-- ---------------------------------------------------------------- ORDER_ITEMS
-- Líneas. El precio, su fuente y el proveedor se llenan al confirmar.
CREATE TABLE ORDER_ITEMS (
    ORDER_ID       VARCHAR2(36) NOT NULL,
    ITEM_ID        VARCHAR2(36) NOT NULL,
    QTY            NUMBER(10)   NOT NULL,
    UNIT_PRICE     NUMBER(12,2),
    PRICE_SOURCE   VARCHAR2(10),
    PRICE_PROVIDER VARCHAR2(3),
    CONSTRAINT PK_ORDER_ITEMS        PRIMARY KEY (ORDER_ID, ITEM_ID),
    CONSTRAINT FK_ORDITEM_ORDER      FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID),
    CONSTRAINT FK_ORDITEM_ITEM       FOREIGN KEY (ITEM_ID) REFERENCES INVENTORY (ID),
    CONSTRAINT CHK_ORDITEM_QTY       CHECK (QTY > 0),
    CONSTRAINT CHK_ORDITEM_PRICE     CHECK (UNIT_PRICE IS NULL OR UNIT_PRICE >= 0),
    CONSTRAINT CHK_ORDITEM_SOURCE    CHECK (PRICE_SOURCE IS NULL OR PRICE_SOURCE IN ('LOCAL', 'LAST_PRICE', 'QUOTE')),
    CONSTRAINT CHK_ORDITEM_PROVIDER  CHECK (PRICE_PROVIDER IS NULL OR PRICE_PROVIDER IN ('FAK', 'ESC', 'BOR'))
);

-- --------------------------------------------------------- INVENTORY_MOVEMENTS
-- Salidas y reposiciones. REFERENCE es única: aplicar dos veces mueve el stock una sola vez (D7).
CREATE TABLE INVENTORY_MOVEMENTS (
    ID              VARCHAR2(36)  NOT NULL,
    ITEM_ID         VARCHAR2(36)  NOT NULL,
    MOVEMENT_TYPE   VARCHAR2(10)  NOT NULL,
    QTY             NUMBER(10)    NOT NULL,
    REFERENCE       VARCHAR2(100) NOT NULL,
    ORDER_ID        VARCHAR2(36),
    RESULTING_STOCK NUMBER(10)    NOT NULL,
    CREATED_AT      TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_INVENTORY_MOVEMENTS PRIMARY KEY (ID),
    CONSTRAINT UQ_INVMOV_REFERENCE    UNIQUE (REFERENCE),
    CONSTRAINT FK_INVMOV_ITEM         FOREIGN KEY (ITEM_ID) REFERENCES INVENTORY (ID),
    CONSTRAINT FK_INVMOV_ORDER        FOREIGN KEY (ORDER_ID) REFERENCES ORDERS (ID),
    CONSTRAINT CHK_INVMOV_TYPE        CHECK (MOVEMENT_TYPE IN ('OUTBOUND', 'RESTOCK')),
    CONSTRAINT CHK_INVMOV_QTY         CHECK (QTY > 0),
    CONSTRAINT CHK_INVMOV_RESULT      CHECK (RESULTING_STOCK >= 0)
);

EXIT
