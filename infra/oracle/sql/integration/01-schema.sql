-- Esquema INTEGRATION_APP: el almacén de solicitudes de corrección. Se ejecuta como INTEGRATION_APP en FREEPDB1.
-- Pertenece a la integración, no al ERP: STORE_APP no tiene permisos aquí, ni INTEGRATION_APP en STORE_APP.
-- Desviación (C2): la final pide una instancia Oracle propia; aquí es otro esquema en la misma instancia.
WHENEVER SQLERROR EXIT SQL.SQLCODE
SET DEFINE OFF

-- ------------------------------------------------------------- ORDER_REQUESTS
-- IDEMPOTENCY_KEY única: repetir la solicitud devuelve la primera.
CREATE TABLE ORDER_REQUESTS (
    ID               VARCHAR2(36)  NOT NULL,
    IDEMPOTENCY_KEY  VARCHAR2(200) NOT NULL,
    ORDER_ID         VARCHAR2(36)  NOT NULL,
    CUSTOMER_ID      VARCHAR2(18),                  -- Id de Salesforce del cliente del pedido, para los eventos approval.requested y correction.applied
    REQUEST_TYPE     VARCHAR2(10)  NOT NULL,
    ITEM_ID          VARCHAR2(36),
    PROVIDER_ABV     VARCHAR2(3),
    QTY              NUMBER(10),
    UNIT_PRICE       NUMBER(12,2),
    AMOUNT           NUMBER(12,2),
    CURRENCY         VARCHAR2(3)   DEFAULT 'MXN' NOT NULL,
    STATUS           VARCHAR2(10)  DEFAULT 'PENDING' NOT NULL,
    REQUESTED_BY     VARCHAR2(100) NOT NULL,
    DECIDED_BY       VARCHAR2(100),
    REASON           VARCHAR2(500),
    EXPIRES_AT       TIMESTAMP WITH TIME ZONE NOT NULL,
    DECIDED_AT       TIMESTAMP WITH TIME ZONE,
    CREATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT       TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_ORDER_REQUESTS     PRIMARY KEY (ID),
    CONSTRAINT UQ_ORDREQ_IDEMPOTENCY UNIQUE (IDEMPOTENCY_KEY),
    CONSTRAINT CHK_ORDREQ_TYPE       CHECK (REQUEST_TYPE IN ('RESTOCK', 'REISSUE')),
    CONSTRAINT CHK_ORDREQ_STATUS     CHECK (STATUS IN ('PENDING', 'APPROVED', 'APPLYING', 'COMPLETED', 'FAILED', 'REJECTED', 'EXPIRED')),
    CONSTRAINT CHK_ORDREQ_PROVIDER   CHECK (PROVIDER_ABV IS NULL OR PROVIDER_ABV IN ('FAK', 'ESC', 'BOR')),
    CONSTRAINT CHK_ORDREQ_QTY        CHECK (QTY IS NULL OR QTY > 0),
    CONSTRAINT CHK_ORDREQ_CURRENCY   CHECK (REGEXP_LIKE(CURRENCY, '^[A-Z]{3}$'))
);
CREATE INDEX IX_ORDREQ_STATUS_EXPIRES ON ORDER_REQUESTS (STATUS, EXPIRES_AT);

-- ------------------------------------------------------- ORDER_REQUEST_EVENTS
-- Historia: cada transición con su actor y su hora.
CREATE TABLE ORDER_REQUEST_EVENTS (
    ID           VARCHAR2(36)  NOT NULL,
    REQUEST_ID   VARCHAR2(36)  NOT NULL,
    FROM_STATUS  VARCHAR2(10),
    TO_STATUS    VARCHAR2(10)  NOT NULL,
    ACTOR        VARCHAR2(100) NOT NULL,
    EVENT_AT     TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    DETAIL       VARCHAR2(1000),
    CONSTRAINT PK_ORDER_REQUEST_EVENTS PRIMARY KEY (ID),
    CONSTRAINT FK_ORDREQEV_REQUEST     FOREIGN KEY (REQUEST_ID) REFERENCES ORDER_REQUESTS (ID),
    CONSTRAINT CHK_ORDREQEV_TO         CHECK (TO_STATUS IN ('PENDING', 'APPROVED', 'APPLYING', 'COMPLETED', 'FAILED', 'REJECTED', 'EXPIRED'))
);
CREATE INDEX IX_ORDREQEV_REQUEST ON ORDER_REQUEST_EVENTS (REQUEST_ID, EVENT_AT);

EXIT
