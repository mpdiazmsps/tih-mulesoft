-- Verificación del esquema INTEGRATION_APP (almacén de solicitudes). Se ejecuta como INTEGRATION_APP;
-- no deja cambios (todo termina en ROLLBACK). Lo corre infra/oracle/verify-schema.ps1 o .sh.
SET SERVEROUTPUT ON SIZE UNLIMITED
SET FEEDBACK OFF HEADING ON PAGESIZE 100 LINESIZE 200
SET DEFINE OFF

PROMPT === INTEGRATION_APP: filas por tabla
SELECT 'ORDER_REQUESTS' AS TABLA, COUNT(*) AS FILAS FROM ORDER_REQUESTS
UNION ALL SELECT 'ORDER_REQUEST_EVENTS', COUNT(*) FROM ORDER_REQUEST_EVENTS;

PROMPT === INTEGRATION_APP: pruebas
DECLARE
  ok   PLS_INTEGER := 0;
  bad  PLS_INTEGER := 0;
  tabs VARCHAR2(4000);
  ins  CONSTANT VARCHAR2(1000) :=
    'INSERT INTO ORDER_REQUESTS (ID, IDEMPOTENCY_KEY, ORDER_ID, REQUEST_TYPE, STATUS, REQUESTED_BY, EXPIRES_AT) ' ||
    'VALUES (:1, ''verify-key'', ''10000000-0000-4000-8000-000000001002'', ''RESTOCK'', ''PENDING'', ''verify'', SYSTIMESTAMP + 1)';
  PROCEDURE check_eq(p_name VARCHAR2, p_got VARCHAR2, p_want VARCHAR2) IS
  BEGIN
    IF p_got = p_want THEN
      DBMS_OUTPUT.PUT_LINE('OK     ' || p_name || ': ' || p_got); ok := ok + 1;
    ELSE
      DBMS_OUTPUT.PUT_LINE('FALLO  ' || p_name || ': ' || p_got || ' (se esperaba ' || p_want || ')'); bad := bad + 1;
    END IF;
  END;
BEGIN
  -- IDEMPOTENCY_KEY repetida
  BEGIN
    EXECUTE IMMEDIATE ins USING '30000000-0000-4000-8000-0000000009f1';
    EXECUTE IMMEDIATE ins USING '30000000-0000-4000-8000-0000000009f2';
    DBMS_OUTPUT.PUT_LINE('FALLO  IDEMPOTENCY_KEY repetida: no dio error'); bad := bad + 1;
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE = -1 THEN DBMS_OUTPUT.PUT_LINE('OK     IDEMPOTENCY_KEY repetida: ORA' || SQLCODE); ok := ok + 1;
    ELSE DBMS_OUTPUT.PUT_LINE('FALLO  IDEMPOTENCY_KEY repetida: ' || SQLERRM); bad := bad + 1; END IF;
  END;
  ROLLBACK;

  -- Sin acceso al ERP
  BEGIN
    EXECUTE IMMEDIATE 'SELECT COUNT(*) FROM STORE_APP.ORDERS' INTO tabs;
    DBMS_OUTPUT.PUT_LINE('FALLO  INTEGRATION_APP ve STORE_APP.ORDERS'); bad := bad + 1;
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE = -942 THEN DBMS_OUTPUT.PUT_LINE('OK     INTEGRATION_APP no ve STORE_APP.ORDERS: ORA' || SQLCODE); ok := ok + 1;
    ELSE DBMS_OUTPUT.PUT_LINE('FALLO  acceso a STORE_APP.ORDERS: ' || SQLERRM); bad := bad + 1; END IF;
  END;

  SELECT LISTAGG(TABLE_NAME, ',') WITHIN GROUP (ORDER BY TABLE_NAME) INTO tabs FROM USER_TABLES;
  check_eq('tablas de INTEGRATION_APP', tabs, 'ORDER_REQUESTS,ORDER_REQUEST_EVENTS');

  DBMS_OUTPUT.PUT_LINE('VERIFY INTEGRATION_APP: ' || ok || ' OK, ' || bad || ' FALLOS');
END;
/
EXIT
